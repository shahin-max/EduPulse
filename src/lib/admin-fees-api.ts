import { request } from "@/lib/api";
import { json, query, type Paginated } from "@/lib/admin-api";

/**
 * Admin endpoints for fees: fee plans, invoices, payments and refunds (Edupulse-api/src/fees).
 * Every function takes the access token first (use with `withToken`).
 * Money arrives as DECIMAL strings ("1500.00") and is sent as strings with at most 2 decimals.
 */

// ---- Enums ----

export type InvoiceStatus = "DRAFT" | "ISSUED" | "PART_PAID" | "PAID" | "VOID";
export const INVOICE_STATUSES: InvoiceStatus[] = ["DRAFT", "ISSUED", "PART_PAID", "PAID", "VOID"];

export type PaymentStatus = "PENDING" | "CONFIRMED" | "FAILED" | "CANCELLED";
export type RefundStatus = PaymentStatus;
/** A PENDING payment or refund can move to one of these. */
export type SettleStatus = "CONFIRMED" | "FAILED" | "CANCELLED";

export type PaymentMethod = "CASH" | "UPI" | "BANK_TRANSFER" | "CARD" | "OTHER";
export const PAYMENT_METHODS: PaymentMethod[] = ["CASH", "UPI", "BANK_TRANSFER", "CARD", "OTHER"];

// ---- Shapes (snake_case, as the API returns them) ----

export type FeePlan = {
  id: number;
  course_id: number;
  /** null = applies to every branch. */
  branch_id: number | null;
  /** null = applies to every batch of the course (in its branch, if any). */
  batch_id: number | null;
  title: string;
  currency: string;
  amount: string;
  is_active: boolean;
  created_at: string;
};

/** GET /fee-plans includes the course and batch; create/update/get-one responses do not. */
export type FeePlanListItem = FeePlan & {
  courses: { id: number; code: string; title: string };
  batches: { id: number; code: string; name: string } | null;
};

export type Refund = {
  id: number;
  payment_id: number;
  amount: string;
  status: RefundStatus;
  idempotency_key: string;
  external_reference: string | null;
  reason: string;
  refunded_at: string | null;
  recorded_by: number | null;
  created_at: string;
};

export type Payment = {
  id: number;
  invoice_id: number;
  branch_id: number;
  amount: string;
  currency: string;
  method: PaymentMethod;
  provider: string | null;
  external_reference: string | null;
  idempotency_key: string;
  /** Set when the payment is CONFIRMED. */
  receipt_number: string | null;
  status: PaymentStatus;
  paid_at: string | null;
  recorded_by: number | null;
  notes: string | null;
  created_at: string;
  payment_refunds: Refund[];
};

export type Invoice = {
  id: number;
  invoice_number: string;
  enrollment_id: number;
  branch_id: number;
  fee_plan_id: number | null;
  description: string | null;
  gross_amount: string;
  discount_amount: string;
  /** Payable amount: gross - discount (generated by the database). */
  amount_due: string | null;
  /** Confirmed payments minus confirmed refunds. */
  amount_paid: string;
  /** Payable minus paid. */
  balance_due: string;
  due_date: string | null;
  status: InvoiceStatus;
  issued_at: string | null;
  created_at: string;
  fee_plans: { id: number; title: string; currency: string } | null;
  enrollments: {
    id: number;
    student_user_id: number;
    student_profiles: { admission_number: string | null; users: { full_name: string } };
    batches: { id: number; code: string; name: string; courses: { id: number; code: string; title: string } };
  };
  payments: Payment[];
};

/** Minimal views of other modules' responses (their own API files belong to other screens). */
export type FeeBatch = {
  id: number;
  branch_id: number;
  course_id: number;
  code: string;
  name: string;
  status: string;
  branches: { id: number; code: string; name: string };
  courses: { id: number; code: string; title: string };
};

export type RosterEntry = {
  id: number; // enrollment id
  status: string;
  enrolled_at: string;
  student_profiles: {
    user_id: number;
    admission_number: string | null;
    users: { full_name: string; email: string | null; mobile: string | null };
  };
};

export type FeeCourse = { id: number; code: string; title: string; status: string };

export type FeeBranch = {
  id: number;
  code: string;
  name: string;
  address: string | null;
  city: string | null;
  state: string | null;
  pincode: string | null;
  phone: string | null;
  email: string | null;
  gstin: string | null;
  is_active: boolean;
};

export type FeeUser = { id: number; full_name: string };

// ---- Inputs (camelCase, as the API expects them) ----

export type ListFeePlansQuery = { courseId?: number; batchId?: number; activeOnly?: boolean };
export type CreateFeePlanInput = { courseId: number; branchId?: number; batchId?: number; title: string; amount: string; currency?: string; isActive?: boolean };
export type UpdateFeePlanInput = { batchId?: number | null; title?: string; amount?: string; isActive?: boolean };

export type ListInvoicesQuery = {
  page?: number; limit?: number; status?: InvoiceStatus; batchId?: number; studentUserId?: number; enrollmentId?: number; overdue?: boolean;
  branchId?: number;
  /** Invoice number, or the student's name, mobile or admission number. */
  search?: string;
};

/** Totals over every invoice matching the filter (drafts and void invoices excluded). */
export type InvoiceSummary = { invoices: number; billed: string; collected: string; outstanding: string };
export type InvoiceList = Paginated<Invoice> & { summary: InvoiceSummary };

/** A row of the payments register (GET /payments). */
export type PaymentListItem = Payment & {
  users: { id: number; full_name: string } | null;
  fee_invoices: {
    id: number;
    invoice_number: string;
    enrollments: {
      student_user_id: number;
      student_profiles: { admission_number: string | null; users: { full_name: string; mobile: string | null } };
      batches: { id: number; code: string; name: string; branches: { id: number; code: string; name: string } };
    };
  };
};

export type ListPaymentsQuery = {
  page?: number; limit?: number;
  /** ISO date-time, inclusive. */
  from?: string;
  /** ISO date-time, exclusive. */
  to?: string;
  branchId?: number; method?: PaymentMethod; status?: PaymentStatus; search?: string;
};

/** Totals over the whole filter: confirmed payments by method, refunds handed back in the period, net. */
export type PaymentsSummary = {
  payments: number;
  collected: string;
  byMethod: { method: PaymentMethod; payments: number; amount: string }[];
  refunds: number;
  refunded: string;
  net: string;
};
export type PaymentList = Paginated<PaymentListItem> & { summary: PaymentsSummary };
export type CreateInvoiceInput = {
  enrollmentId: number;
  feePlanId?: number;
  description?: string;
  /** Required unless a fee plan is given. */
  grossAmount?: string;
  discountAmount?: string;
  /** YYYY-MM-DD */
  dueDate?: string;
  issue?: boolean;
};
/** Only DRAFT invoices can be edited. */
export type UpdateInvoiceInput = { description?: string; grossAmount?: string; discountAmount?: string; dueDate?: string | null };

export type RecordPaymentInput = {
  amount: string;
  method: PaymentMethod;
  /** Unique per payment attempt; re-sending the same request returns the original payment. */
  idempotencyKey: string;
  status?: "PENDING" | "CONFIRMED";
  provider?: string;
  externalReference?: string;
  /** ISO date-time. */
  paidAt?: string;
  notes?: string;
};
export type UpdatePaymentStatusInput = { status: SettleStatus; paidAt?: string };
export type CreateRefundInput = { amount: string; reason: string; idempotencyKey: string; status?: "PENDING" | "CONFIRMED"; externalReference?: string };

// ---- Endpoints ----

export const feePlansApi = {
  list: (token: string, params: ListFeePlansQuery = {}) => request<FeePlanListItem[]>(`/fee-plans${query(params)}`, { token }),
  get: (token: string, id: number) => request<FeePlan>(`/fee-plans/${id}`, { token }),
  create: (token: string, input: CreateFeePlanInput) => request<FeePlan>("/fee-plans", { token, ...json("POST", input) }),
  update: (token: string, id: number, input: UpdateFeePlanInput) => request<FeePlan>(`/fee-plans/${id}`, { token, ...json("PATCH", input) }),
};

export const invoicesApi = {
  list: (token: string, params: ListInvoicesQuery = {}) => request<InvoiceList>(`/fee-invoices${query(params)}`, { token }),
  get: (token: string, id: number) => request<Invoice>(`/fee-invoices/${id}`, { token }),
  create: (token: string, input: CreateInvoiceInput) => request<Invoice>("/fee-invoices", { token, ...json("POST", input) }),
  update: (token: string, id: number, input: UpdateInvoiceInput) => request<Invoice>(`/fee-invoices/${id}`, { token, ...json("PATCH", input) }),
  issue: (token: string, id: number) => request<Invoice>(`/fee-invoices/${id}/issue`, { token, method: "POST" }),
  void: (token: string, id: number) => request<Invoice>(`/fee-invoices/${id}/void`, { token, method: "POST" }),
  recordPayment: (token: string, id: number, input: RecordPaymentInput) => request<Payment>(`/fee-invoices/${id}/payments`, { token, ...json("POST", input) }),
};

export const paymentsApi = {
  list: (token: string, params: ListPaymentsQuery = {}) => request<PaymentList>(`/payments${query(params)}`, { token }),
  get: (token: string, id: number) => request<Payment>(`/payments/${id}`, { token }),
  setStatus: (token: string, id: number, input: UpdatePaymentStatusInput) => request<Payment>(`/payments/${id}/status`, { token, ...json("PATCH", input) }),
  refund: (token: string, id: number, input: CreateRefundInput) => request<Refund>(`/payments/${id}/refunds`, { token, ...json("POST", input) }),
  setRefundStatus: (token: string, refundId: number, status: SettleStatus) => request<Refund>(`/refunds/${refundId}/status`, { token, ...json("PATCH", { status }) }),
};

/** Lookups from other modules that the fee screens need. */
export const feeLookupsApi = {
  batches: (token: string, params: { courseId?: number; branchId?: number } = {}) =>
    request<Paginated<FeeBatch>>(`/batches${query({ ...params, limit: 100 })}`, { token }),
  roster: (token: string, batchId: number) => request<RosterEntry[]>(`/batches/${batchId}/students`, { token }),
  courses: (token: string) => request<FeeCourse[]>("/courses?includeAll=true", { token }),
  branches: (token: string) => request<FeeBranch[]>("/branches?includeInactive=true", { token }),
  branch: (token: string, id: number) => request<FeeBranch>(`/branches/${id}`, { token }),
  user: (token: string, id: number) => request<FeeUser>(`/users/${id}`, { token }),
};

// ---- Money helpers (exact maths in paise, never floats) ----

/** "1500.50" -> 150050. Invalid input -> NaN. */
export function toPaise(value: string | null | undefined): number {
  if (value === null || value === undefined) return 0;
  const text = String(value).trim();
  if (!/^-?\d+(\.\d{1,2})?$/.test(text)) return Number.NaN;
  const negative = text.startsWith("-");
  const [whole, fraction = ""] = text.replace("-", "").split(".");
  const paise = Number(whole) * 100 + Number(fraction.padEnd(2, "0"));
  return negative ? -paise : paise;
}

/** 150050 -> "1500.50" (the format the API accepts). */
export const fromPaise = (paise: number) => `${paise < 0 ? "-" : ""}${Math.floor(Math.abs(paise) / 100)}.${String(Math.abs(paise) % 100).padStart(2, "0")}`;

/** What the DTOs accept: up to 10 integer digits and 2 decimals. */
export const MONEY_PATTERN = "\\d{1,10}(\\.\\d{1,2})?";
export const isMoney = (value: string) => new RegExp(`^${MONEY_PATTERN}$`).test(value.trim());
