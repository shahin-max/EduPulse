import type { Metadata } from "next";
import { contact, GEO, MAPS_URL, OPENING_HOURS, postalAddress, socials } from "@/lib/site";

/** Public address of the website, for canonical URLs, the sitemap and social previews. */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL ?? "http://localhost:3000").replace(/\/+$/, "");

/** The one address search engines should list. Every other copy (staging, previews, localhost) is kept out of search. */
export const PRODUCTION_HOST = "edupulseindia.com";

/** True only on the live site: staging and local copies tell search engines not to index them. */
export const INDEXABLE = (() => {
  try { return new URL(SITE_URL).hostname === PRODUCTION_HOST; } catch { return false; }
})();

export const SITE_NAME = "EduPulse Academy";

/** The home page's <title> (the hero still shows the "Learn Today, Lead Tomorrow" tagline). */
export const HOME_TITLE = "EduPulse Academy Aligarh | NEET, JEE, AISSEE & AMU Entrance Coaching";

/** The branded link-preview picture, generated by app/opengraph-image.tsx. */
export const SHARE_IMAGE = "/opengraph-image";

/** Absolute URL of a site path, e.g. "/faculty" → "https://edupulseindia.com/faculty". */
export const absoluteUrl = (path: string) => `${SITE_URL}${path === "/" ? "" : path}`;

/**
 * Metadata for a public page: its title and description, its canonical address (so Google lists one URL per page)
 * and matching link previews for WhatsApp, Facebook and X. The share image comes from app/opengraph-image.
 */
export function pageMetadata({ title, description, path }: { title?: string; description?: string; path: string }): Metadata {
  const shareTitle = title ? `${title} | ${SITE_NAME}` : HOME_TITLE;
  // A page's own openGraph replaces the layout's, so the share image is named here for every page.
  const images = [{ url: SHARE_IMAGE, width: 1200, height: 630, alt: "EduPulse Academy, Aligarh: Learn Today, Lead Tomorrow" }];
  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    openGraph: { type: "website", siteName: SITE_NAME, locale: "en_IN", url: path, title: shareTitle, description, images },
    twitter: { card: "summary_large_image", title: shareTitle, description, images },
  };
}

/** schema.org data for search engines (rendered as JSON-LD on the home page). */
export const organizationJsonLd = {
  "@context": "https://schema.org",
  "@type": ["EducationalOrganization", "LocalBusiness"],
  "@id": `${SITE_URL}/#organization`,
  name: SITE_NAME,
  slogan: "Learn Today, Lead Tomorrow",
  description: "Coaching institute in Aligarh for school tuition (Classes 6-10), AISSEE Sainik School & RMS, JEE, NEET, AMU & JMI entrance, CUET, NDA/CDS, IMU-CET and Spoken English.",
  url: SITE_URL,
  logo: `${SITE_URL}/edupulse-logo.jpeg`,
  image: `${SITE_URL}${SHARE_IMAGE}`,
  email: contact.email,
  telephone: contact.phones[0]?.tel,
  address: { "@type": "PostalAddress", ...postalAddress },
  geo: { "@type": "GeoCoordinates", ...GEO },
  hasMap: MAPS_URL,
  openingHoursSpecification: [{
    "@type": "OpeningHoursSpecification",
    dayOfWeek: ["Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday"],
    opens: OPENING_HOURS.opens,
    closes: OPENING_HOURS.closes,
  }],
  areaServed: { "@type": "City", name: "Aligarh" },
  contactPoint: contact.phones.map(p => ({ "@type": "ContactPoint", telephone: p.tel, contactType: "admissions", areaServed: "IN", availableLanguage: ["en", "hi"] })),
  sameAs: Object.values(socials),
};

/** The website itself, linked to the academy (helps Google show the site name in results). */
export const websiteJsonLd = {
  "@context": "https://schema.org",
  "@type": "WebSite",
  "@id": `${SITE_URL}/#website`,
  name: SITE_NAME,
  url: SITE_URL,
  inLanguage: "en-IN",
  publisher: { "@id": `${SITE_URL}/#organization` },
};

/** Breadcrumbs for a page, e.g. Home › Courses › NEET. */
export function breadcrumbJsonLd(trail: { name: string; path: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: trail.map((t, i) => ({ "@type": "ListItem", position: i + 1, name: t.name, item: absoluteUrl(t.path) })),
  };
}

/** A program page as a schema.org Course, offered in person in Aligarh. */
export function courseJsonLd({ title, description, path }: { title: string; description: string; path: string }) {
  return {
    "@context": "https://schema.org",
    "@type": "Course",
    name: title,
    description,
    url: absoluteUrl(path),
    inLanguage: "en-IN",
    provider: { "@type": "EducationalOrganization", "@id": `${SITE_URL}/#organization`, name: SITE_NAME, sameAs: SITE_URL },
    hasCourseInstance: { "@type": "CourseInstance", courseMode: "Onsite", location: { "@type": "Place", name: SITE_NAME, address: { "@type": "PostalAddress", ...postalAddress }, hasMap: MAPS_URL } },
  };
}

/** Questions and answers shown on a page, as schema.org FAQPage. */
export function faqJsonLd(faqs: { q: string; a: string }[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map(f => ({ "@type": "Question", name: f.q, acceptedAnswer: { "@type": "Answer", text: f.a } })),
  };
}

/** JSON-LD as a safe <script> body (no "</script>" break-out). */
export const jsonLd = (data: unknown) => ({ __html: JSON.stringify(data).replace(/</g, "\\u003c") });
